import { useMemo, useRef, useState } from 'react';
import { useTranslation } from 'react-i18next';
import {
  AlertTriangle,
  CheckCircle2,
  Download,
  FileJson,
  FileSpreadsheet,
  FileUp,
  Loader2,
  RotateCcw,
  UploadCloud,
  XCircle
} from 'lucide-react';
import PageHeader from '../../components/admin/ui/PageHeader';
import DataTable from '../../components/admin/ui/DataTable';
import { useAuth } from '../../context/AuthContext';
import { useToast } from '../../context/ToastContext';
import {
  checkAdminImportDuplicates,
  downloadAdminExport,
  downloadAdminImportTemplate,
  importAdminResources
} from '../../lib/api';
import {
  MAX_IMPORT_FILE_BYTES,
  applyDuplicates,
  buildImportPreview,
  buildImportReportCsv,
  chunkRows,
  downloadBlob,
  parseImportFile
} from '../../lib/importExport';
import { formatNumber } from '../../lib/utils';

const EXPORTS = [
  { kind: 'resources', format: 'json', icon: FileJson, labelKey: 'admin.importExport.export.resourcesJson' },
  { kind: 'resources', format: 'csv', icon: FileSpreadsheet, labelKey: 'admin.importExport.export.resourcesCsv' },
  { kind: 'categories', format: 'json', icon: FileJson, labelKey: 'admin.importExport.export.categoriesJson' },
  { kind: 'alternatives', format: 'json', icon: FileJson, labelKey: 'admin.importExport.export.alternativesJson' }
];

const PREVIEW_LIMIT = 300;

function errorText(error, t) {
  if (!error) return '';
  const key = error.message || '';
  return key.startsWith('admin.') ? t(key) : key || t('admin.importExport.errors.generic');
}

function statusLabel(status, t) {
  return t(`admin.importExport.status.${status || 'pending'}`);
}

function ResultPill({ status }) {
  const { t } = useTranslation();
  const styles = {
    created: 'bg-emerald-50 text-emerald-800 ring-emerald-200 dark:bg-emerald-500/10 dark:text-emerald-200 dark:ring-emerald-500/30',
    updated: 'bg-brand-50 text-brand-800 ring-brand-200 dark:bg-brand-500/10 dark:text-brand-200 dark:ring-brand-500/30',
    skipped: 'bg-amber-50 text-amber-900 ring-amber-200 dark:bg-amber-500/10 dark:text-amber-200 dark:ring-amber-500/30',
    failed: 'bg-rose-50 text-rose-800 ring-rose-200 dark:bg-rose-500/10 dark:text-rose-200 dark:ring-rose-500/30',
    pending: 'bg-sand-100 text-ink-muted ring-sand-300 dark:bg-white/5 dark:text-ink-soft dark:ring-white/10'
  };
  return (
    <span className={`chip ${styles[status] || styles.pending}`}>
      {statusLabel(status, t)}
    </span>
  );
}

/**
 * Admin → Import / Export.
 *
 * Exports are generated by the server. Imports are parsed and previewed in the
 * browser with the resource form's zod schema, then sent in batches of 400.
 * The server re-validates, skips/updates duplicates by sourceUrl, and always
 * saves new rows as drafts.
 */
export default function AdminImportExportPage() {
  const { t, i18n } = useTranslation();
  const { user } = useAuth();
  const { push } = useToast();
  const inputRef = useRef(null);

  const [downloading, setDownloading] = useState('');
  const [downloadError, setDownloadError] = useState('');

  const [file, setFile] = useState(null);
  const [dragging, setDragging] = useState(false);
  const [parsing, setParsing] = useState(false);
  const [rows, setRows] = useState([]);
  const [parseError, setParseError] = useState('');
  const [duplicateWarning, setDuplicateWarning] = useState('');
  const [checkingDuplicates, setCheckingDuplicates] = useState(false);
  const [mode, setMode] = useState('skip');

  const [importing, setImporting] = useState(false);
  const [progress, setProgress] = useState({ done: 0, total: 0 });
  const [importError, setImportError] = useState('');
  const [summary, setSummary] = useState(null);

  const stats = useMemo(
    () => ({
      valid: rows.filter((row) => row.valid).length,
      invalid: rows.filter((row) => !row.valid).length,
      duplicates: rows.filter((row) => row.duplicate).length,
      display: rows.slice(0, PREVIEW_LIMIT)
    }),
    [rows]
  );

  async function tokenOrThrow() {
    if (!user) throw new Error(t('admin.importExport.errors.signIn'));
    return user.getIdToken();
  }

  async function handleDownload(kind, format) {
    const key = `${kind}-${format}`;
    if (downloading) return;
    setDownloading(key);
    setDownloadError('');
    try {
      const token = await tokenOrThrow();
      const { blob, filename } = await downloadAdminExport(kind, format, token);
      downloadBlob(blob, filename);
      push(t('admin.importExport.export.success'), { type: 'success' });
    } catch (error) {
      console.warn('[admin-import-export] export failed:', error);
      setDownloadError(error.message || t('admin.importExport.export.error'));
    } finally {
      setDownloading('');
    }
  }

  async function handleTemplate(format) {
    const key = `template-${format}`;
    if (downloading) return;
    setDownloading(key);
    setDownloadError('');
    try {
      const token = await tokenOrThrow();
      const { blob, filename } = await downloadAdminImportTemplate(format, token);
      downloadBlob(blob, filename);
      push(t('admin.importExport.template.success'), { type: 'success' });
    } catch (error) {
      console.warn('[admin-import-export] template failed:', error);
      setDownloadError(error.message || t('admin.importExport.export.error'));
    } finally {
      setDownloading('');
    }
  }

  async function checkDuplicates(previewRows) {
    const urls = Array.from(
      new Set(
        previewRows
          .filter((row) => row.valid && row.sourceUrl)
          .map((row) => row.sourceUrl)
      )
    );
    if (!urls.length) return;

    setCheckingDuplicates(true);
    setDuplicateWarning('');
    try {
      const token = await tokenOrThrow();
      const matches = {};
      for (const group of chunkRows(urls, 400)) {
        // eslint-disable-next-line no-await-in-loop
        const response = await checkAdminImportDuplicates(group, token);
        Object.assign(matches, response.matches || {});
      }
      setRows((current) => applyDuplicates(current, matches));
    } catch (error) {
      console.warn('[admin-import-export] duplicate check failed:', error);
      setDuplicateWarning(t('admin.importExport.errors.duplicateCheck'));
    } finally {
      setCheckingDuplicates(false);
    }
  }

  async function loadFile(nextFile) {
    if (!nextFile || importing || parsing) return;
    setParsing(true);
    setParseError('');
    setImportError('');
    setSummary(null);
    setFile(nextFile);
    setRows([]);
    setDuplicateWarning('');

    try {
      const rawRows = await parseImportFile(nextFile);
      const previewRows = buildImportPreview(rawRows, i18n);
      setRows(previewRows);
      await checkDuplicates(previewRows);
    } catch (error) {
      setParseError(errorText(error, t));
      setFile(null);
    } finally {
      setParsing(false);
      if (inputRef.current) inputRef.current.value = '';
    }
  }

  function resetImport() {
    if (importing || parsing) return;
    setFile(null);
    setRows([]);
    setParseError('');
    setImportError('');
    setSummary(null);
    setProgress({ done: 0, total: 0 });
    setMode('skip');
    setDuplicateWarning('');
    setCheckingDuplicates(false);
    if (inputRef.current) inputRef.current.value = '';
  }

  async function handleImport() {
    if (importing || parsing || checkingDuplicates || !rows.length) return;
    const validRows = rows.filter((row) => row.valid);
    if (!validRows.length) {
      setImportError(t('admin.importExport.errors.allInvalid'));
      return;
    }

    setImporting(true);
    setImportError('');
    setSummary(null);
    setRows((current) =>
      current.map((row) => ({ ...row, finalStatus: null, result: null, errorMessage: '' }))
    );
    setProgress({ done: 0, total: validRows.length });

    const results = new Map();
    try {
      const token = await tokenOrThrow();
      let done = 0;

      for (const group of chunkRows(validRows, 400)) {
        try {
          // eslint-disable-next-line no-await-in-loop
          const response = await importAdminResources(
            {
              mode,
              rows: group.map((row) => ({ index: row.index, resource: row.payload }))
            },
            token
          );
          (response.results || []).forEach((result) => results.set(result.index, result));
        } catch (error) {
          console.warn('[admin-import-export] batch failed:', error);
          group.forEach((row) =>
            results.set(row.index, {
              index: row.index,
              status: 'failed',
              message: error.message || t('admin.importExport.errors.batchFailed')
            })
          );
        }
        done += group.length;
        setProgress({ done, total: validRows.length });
      }

      const nextRows = rows.map((row) => {
        if (!row.valid) {
          return {
            ...row,
            finalStatus: 'failed',
            errorMessage: row.errors.join('; ')
          };
        }
        const result = results.get(row.index);
        if (!result) {
          return {
            ...row,
            finalStatus: 'failed',
            errorMessage: t('admin.importExport.errors.batchFailed')
          };
        }
        return {
          ...row,
          result,
          finalStatus: result.status,
          errorMessage: result.message || ''
        };
      });

      setRows(nextRows);
      const nextSummary = nextRows.reduce(
        (totals, row) => {
          totals.total += 1;
          if (row.finalStatus === 'created') totals.created += 1;
          else if (row.finalStatus === 'updated') totals.updated += 1;
          else if (row.finalStatus === 'skipped') totals.skipped += 1;
          else totals.failed += 1;
          return totals;
        },
        { total: 0, created: 0, updated: 0, skipped: 0, failed: 0 }
      );
      setSummary(nextSummary);
      push(t('admin.importExport.import.done'), { type: 'success' });
    } catch (error) {
      console.warn('[admin-import-export] import failed:', error);
      setImportError(error.message || t('admin.importExport.errors.importFailed'));
    } finally {
      setImporting(false);
    }
  }

  function downloadReport() {
    const csv = buildImportReportCsv(rows);
    downloadBlob(
      new Blob([csv], { type: 'text/csv;charset=utf-8' }),
      `openlearn-import-report-${new Date().toISOString().slice(0, 10)}.csv`
    );
  }

  const previewColumns = [
    {
      key: 'row',
      header: t('admin.importExport.preview.columns.row'),
      className: 'w-12 text-xs text-ink-muted',
      render: (row) => formatNumber(row.index + 1, i18n.language)
    },
    {
      key: 'title',
      header: t('admin.importExport.preview.columns.title'),
      render: (row) => (
        <div className="min-w-[12rem] max-w-xs">
          <p className="truncate font-semibold text-ink">{row.title}</p>
          <p className="truncate text-[11px] text-ink-muted" dir="ltr">
            {row.sourceUrl || '—'}
          </p>
        </div>
      )
    },
    {
      key: 'type',
      header: t('admin.importExport.preview.columns.type'),
      render: (row) => {
        const key = `type.${row.type}`;
        return <span className="chip bg-sand-100 text-ink-soft">{i18n.exists(key) ? t(key) : row.type || '—'}</span>;
      }
    },
    {
      key: 'validation',
      header: t('admin.importExport.preview.columns.validation'),
      render: (row) =>
        row.valid ? (
          <span className="inline-flex items-center gap-1.5 text-xs font-semibold text-emerald-700 dark:text-emerald-300">
            <CheckCircle2 className="h-3.5 w-3.5" aria-hidden="true" />
            {t('admin.importExport.preview.valid')}
          </span>
        ) : (
          <div className="max-w-xs">
            <span className="inline-flex items-center gap-1.5 text-xs font-semibold text-rose-700 dark:text-rose-300">
              <XCircle className="h-3.5 w-3.5" aria-hidden="true" />
              {t('admin.importExport.preview.invalid')}
            </span>
            <p className="mt-1 text-[11px] leading-relaxed text-ink-muted">
              {row.errors.slice(0, 2).join(' · ')}
            </p>
          </div>
        )
    },
    {
      key: 'duplicate',
      header: t('admin.importExport.preview.columns.duplicate'),
      render: (row) => {
        if (row.finalStatus) return <ResultPill status={row.finalStatus} />;
        if (!row.duplicate) {
          return (
            <span className="chip bg-sand-100 text-ink-muted ring-sand-300 dark:bg-white/5 dark:text-ink-soft dark:ring-white/10">
              {t('admin.importExport.preview.new')}
            </span>
          );
        }
        return (
          <div className="max-w-[13rem]">
            <span className="chip bg-amber-50 text-amber-900 ring-amber-200 dark:bg-amber-500/10 dark:text-amber-200 dark:ring-amber-500/30">
              {mode === 'update'
                ? t('admin.importExport.preview.duplicateUpdate')
                : t('admin.importExport.preview.duplicateSkip')}
            </span>
            <p className="mt-1 truncate text-[11px] text-ink-muted" title={row.duplicate.title}>
              {row.duplicate.title || row.duplicate.id}
            </p>
          </div>
        );
      }
    }
  ];

  return (
    <div>
      <PageHeader
        title={t('admin.importExport.title')}
        description={t('admin.importExport.subtitle')}
      />

      {downloadError && (
        <div className="mb-4 flex items-start gap-2 rounded-2xl border border-rose-200 bg-rose-50 px-4 py-3 text-sm text-rose-700 dark:border-rose-500/40 dark:bg-rose-500/10 dark:text-rose-300">
          <AlertTriangle className="mt-0.5 h-4 w-4 shrink-0" aria-hidden="true" />
          <span>{downloadError}</span>
        </div>
      )}

      <div className="grid gap-6 xl:grid-cols-2">
        <section className="card p-5 sm:p-6">
          <h2 className="flex items-center gap-2 font-display text-xl font-semibold text-ink">
            <Download className="h-5 w-5 text-brand-700" aria-hidden="true" />
            {t('admin.importExport.export.title')}
          </h2>
          <p className="mt-2 text-sm leading-relaxed text-ink-soft">
            {t('admin.importExport.export.text')}
          </p>
          <div className="mt-5 grid gap-2 sm:grid-cols-2">
            {EXPORTS.map((item) => {
              const Icon = item.icon;
              const key = `${item.kind}-${item.format}`;
              return (
                <button
                  key={key}
                  type="button"
                  onClick={() => handleDownload(item.kind, item.format)}
                  disabled={Boolean(downloading)}
                  className="btn-secondary justify-start"
                >
                  {downloading === key ? (
                    <Loader2 className="h-4 w-4 animate-spin" aria-hidden="true" />
                  ) : (
                    <Icon className="h-4 w-4" aria-hidden="true" />
                  )}
                  {t(item.labelKey)}
                </button>
              );
            })}
          </div>
        </section>

        <section className="card p-5 sm:p-6">
          <h2 className="flex items-center gap-2 font-display text-xl font-semibold text-ink">
            <FileUp className="h-5 w-5 text-brand-700" aria-hidden="true" />
            {t('admin.importExport.template.title')}
          </h2>
          <p className="mt-2 text-sm leading-relaxed text-ink-soft">
            {t('admin.importExport.template.text')}
          </p>
          <div className="mt-5 flex flex-wrap gap-2">
            <button
              type="button"
              onClick={() => handleTemplate('json')}
              disabled={Boolean(downloading)}
              className="btn-secondary"
            >
              {downloading === 'template-json' ? (
                <Loader2 className="h-4 w-4 animate-spin" aria-hidden="true" />
              ) : (
                <FileJson className="h-4 w-4" aria-hidden="true" />
              )}
              {t('admin.importExport.template.json')}
            </button>
            <button
              type="button"
              onClick={() => handleTemplate('csv')}
              disabled={Boolean(downloading)}
              className="btn-secondary"
            >
              {downloading === 'template-csv' ? (
                <Loader2 className="h-4 w-4 animate-spin" aria-hidden="true" />
              ) : (
                <FileSpreadsheet className="h-4 w-4" aria-hidden="true" />
              )}
              {t('admin.importExport.template.csv')}
            </button>
          </div>
          <p className="mt-4 rounded-2xl border border-sand-200 bg-sand-50 px-4 py-3 text-xs leading-relaxed text-ink-muted">
            {t('admin.importExport.template.hint')}
          </p>
        </section>
      </div>

      <section className="card mt-6 p-5 sm:p-6">
        <div className="flex flex-wrap items-start justify-between gap-3">
          <div>
            <h2 className="flex items-center gap-2 font-display text-xl font-semibold text-ink">
              <UploadCloud className="h-5 w-5 text-brand-700" aria-hidden="true" />
              {t('admin.importExport.import.title')}
            </h2>
            <p className="mt-2 max-w-3xl text-sm leading-relaxed text-ink-soft">
              {t('admin.importExport.import.text')}
            </p>
          </div>
          {rows.length > 0 && (
            <button
              type="button"
              onClick={resetImport}
              disabled={importing || parsing}
              className="btn-secondary btn-sm"
            >
              <RotateCcw className="h-3.5 w-3.5" aria-hidden="true" />
              {t('admin.importExport.import.clear')}
            </button>
          )}
        </div>

        <label
          htmlFor="import-file"
          onDragOver={(event) => {
            event.preventDefault();
            setDragging(true);
          }}
          onDragLeave={() => setDragging(false)}
          onDrop={(event) => {
            event.preventDefault();
            setDragging(false);
            if (importing || parsing) return;
            const dropped = event.dataTransfer.files?.[0];
            if (dropped) loadFile(dropped);
          }}
          className={`mt-5 flex cursor-pointer flex-col items-center justify-center rounded-3xl border-2 border-dashed px-6 py-9 text-center transition ${
            importing ? 'cursor-not-allowed opacity-60' : ''
          } ${
            dragging
              ? 'border-accent-500 bg-accent-50/70 dark:bg-accent-500/10'
              : 'border-sand-300 bg-sand-50/60 hover:border-brand-300 hover:bg-sand-50'
          }`}
        >
          <span className="grid h-12 w-12 place-items-center rounded-2xl bg-surface text-brand-700 shadow-soft">
            {parsing ? (
              <Loader2 className="h-5 w-5 animate-spin" aria-hidden="true" />
            ) : (
              <UploadCloud className="h-5 w-5" aria-hidden="true" />
            )}
          </span>
          <span className="mt-3 font-display text-base font-semibold text-ink">
            {parsing ? t('admin.importExport.import.parsing') : t('admin.importExport.import.dropTitle')}
          </span>
          <span className="mt-1 max-w-md text-xs leading-relaxed text-ink-muted">
            {t('admin.importExport.import.dropText', {
              size: Math.round(MAX_IMPORT_FILE_BYTES / (1024 * 1024))
            })}
          </span>
          <span className="mt-3 inline-flex items-center gap-1.5 rounded-full bg-surface px-3 py-1.5 text-xs font-semibold text-brand-800 ring-1 ring-sand-300">
            <FileUp className="h-3.5 w-3.5" aria-hidden="true" />
            {t('admin.importExport.import.browse')}
          </span>
          <input
            ref={inputRef}
            id="import-file"
            type="file"
            accept=".json,.csv,application/json,text/csv"
            disabled={importing || parsing}
            className="sr-only"
            onChange={(event) => loadFile(event.target.files?.[0])}
          />
        </label>

        {file && (
          <p className="mt-3 flex flex-wrap items-center gap-2 text-xs text-ink-muted">
            <FileJson className="h-3.5 w-3.5" aria-hidden="true" />
            <span className="font-semibold text-ink-soft">{file.name}</span>
            <span>·</span>
            <span>{formatNumber(Math.ceil(file.size / 1024), i18n.language)} KB</span>
            {checkingDuplicates && (
              <span className="inline-flex items-center gap-1.5 text-brand-700 dark:text-brand-300">
                <Loader2 className="h-3 w-3 animate-spin" aria-hidden="true" />
                {t('admin.importExport.import.checkingDuplicates')}
              </span>
            )}
          </p>
        )}

        {parseError && (
          <div className="mt-4 flex items-start gap-2 rounded-2xl border border-rose-200 bg-rose-50 px-4 py-3 text-sm text-rose-700 dark:border-rose-500/40 dark:bg-rose-500/10 dark:text-rose-300">
            <AlertTriangle className="mt-0.5 h-4 w-4 shrink-0" aria-hidden="true" />
            <span>{parseError}</span>
          </div>
        )}

        {duplicateWarning && (
          <div className="mt-4 flex items-start gap-2 rounded-2xl border border-amber-200 bg-amber-50 px-4 py-3 text-xs leading-relaxed text-amber-900 dark:border-amber-500/40 dark:bg-amber-500/10 dark:text-amber-200">
            <AlertTriangle className="mt-0.5 h-4 w-4 shrink-0" aria-hidden="true" />
            <span>{duplicateWarning}</span>
          </div>
        )}

        {rows.length > 0 && (
          <div className="mt-6 space-y-5">
            <div className="flex flex-wrap items-center gap-2">
              <span className="chip bg-emerald-50 text-emerald-800 ring-emerald-200 dark:bg-emerald-500/10 dark:text-emerald-200 dark:ring-emerald-500/30">
                {t('admin.importExport.preview.validCount', { count: stats.valid })}
              </span>
              <span className="chip bg-rose-50 text-rose-800 ring-rose-200 dark:bg-rose-500/10 dark:text-rose-200 dark:ring-rose-500/30">
                {t('admin.importExport.preview.errorCount', { count: stats.invalid })}
              </span>
              <span className="chip bg-amber-50 text-amber-900 ring-amber-200 dark:bg-amber-500/10 dark:text-amber-200 dark:ring-amber-500/30">
                {t('admin.importExport.preview.duplicateCount', { count: stats.duplicates })}
              </span>
              <span className="text-xs text-ink-muted">
                {t('admin.importExport.preview.totalRows', {
                  count: formatNumber(rows.length, i18n.language)
                })}
              </span>
            </div>

            <fieldset>
              <legend className="text-sm font-semibold text-ink">
                {t('admin.importExport.options.title')}
              </legend>
              <p className="mt-1 text-xs text-ink-muted">{t('admin.importExport.options.hint')}</p>
              <div className="mt-3 grid gap-2 sm:grid-cols-2">
                {[
                  {
                    value: 'skip',
                    title: t('admin.importExport.options.skip'),
                    text: t('admin.importExport.options.skipHint')
                  },
                  {
                    value: 'update',
                    title: t('admin.importExport.options.update'),
                    text: t('admin.importExport.options.updateHint')
                  }
                ].map((option) => (
                  <label
                    key={option.value}
                    className={`flex cursor-pointer items-start gap-3 rounded-2xl border px-4 py-3 transition ${
                      mode === option.value
                        ? 'border-accent-400 bg-accent-50/60 dark:border-accent-500/50 dark:bg-accent-500/10'
                        : 'border-sand-200 bg-surface hover:border-sand-300'
                    }`}
                  >
                    <input
                      type="radio"
                      name="import-mode"
                      value={option.value}
                      checked={mode === option.value}
                      onChange={() => setMode(option.value)}
                      disabled={importing}
                      className="mt-0.5 h-4 w-4 accent-accent-600"
                    />
                    <span>
                      <span className="block text-sm font-semibold text-ink">{option.title}</span>
                      <span className="mt-0.5 block text-xs leading-relaxed text-ink-muted">
                        {option.text}
                      </span>
                    </span>
                  </label>
                ))}
              </div>
              <p className="mt-2 text-[11px] text-ink-muted">
                {t('admin.importExport.options.draftNote')}
              </p>
            </fieldset>

            {importError && (
              <div className="flex items-start gap-2 rounded-2xl border border-rose-200 bg-rose-50 px-4 py-3 text-sm text-rose-700 dark:border-rose-500/40 dark:bg-rose-500/10 dark:text-rose-300">
                <AlertTriangle className="mt-0.5 h-4 w-4 shrink-0" aria-hidden="true" />
                <span>{importError}</span>
              </div>
            )}

            {importing && (
              <div aria-live="polite">
                <div className="flex items-center justify-between gap-3 text-xs text-ink-muted">
                  <span>{t('admin.importExport.import.progress')}</span>
                  <span className="font-mono">
                    {formatNumber(progress.done, i18n.language)} /{' '}
                    {formatNumber(progress.total, i18n.language)}
                  </span>
                </div>
                <div className="mt-1.5 h-2 overflow-hidden rounded-full bg-sand-200">
                  <div
                    className="h-full rounded-full bg-accent-500 transition-all"
                    style={{
                      width: `${progress.total ? Math.round((progress.done / progress.total) * 100) : 0}%`
                    }}
                  />
                </div>
              </div>
            )}

            {summary && (
              <div className="rounded-2xl border border-sand-200 bg-sand-50/70 p-4">
                <h3 className="font-display text-base font-semibold text-ink">
                  {t('admin.importExport.summary.title')}
                </h3>
                <div className="mt-3 grid grid-cols-2 gap-2 sm:grid-cols-5">
                  {[
                    ['created', summary.created],
                    ['updated', summary.updated],
                    ['skipped', summary.skipped],
                    ['failed', summary.failed],
                    ['total', summary.total]
                  ].map(([key, value]) => (
                    <div key={key} className="rounded-xl border border-sand-200 bg-surface px-3 py-2.5">
                      <p className="text-[10px] font-bold uppercase tracking-[0.12em] text-ink-muted">
                        {statusLabel(key, t)}
                      </p>
                      <p className="mt-0.5 font-display text-xl font-semibold text-ink">
                        {formatNumber(value, i18n.language)}
                      </p>
                    </div>
                  ))}
                </div>
              </div>
            )}

            <div className="flex flex-wrap gap-2">
              <button
                type="button"
                onClick={handleImport}
                disabled={importing || parsing || checkingDuplicates || stats.valid === 0}
                className="btn-primary"
              >
                {importing ? (
                  <Loader2 className="h-4 w-4 animate-spin" aria-hidden="true" />
                ) : (
                  <UploadCloud className="h-4 w-4" aria-hidden="true" />
                )}
                {importing
                  ? t('admin.importExport.import.importing')
                  : t('admin.importExport.import.importValid', { count: stats.valid })}
              </button>
              <button type="button" onClick={downloadReport} className="btn-secondary">
                <Download className="h-4 w-4" aria-hidden="true" />
                {t('admin.importExport.import.downloadReport')}
              </button>
            </div>

            <div>
              <div className="mb-2 flex flex-wrap items-center justify-between gap-2">
                <h3 className="font-display text-base font-semibold text-ink">
                  {t('admin.importExport.preview.title')}
                </h3>
                {rows.length > PREVIEW_LIMIT && (
                  <p className="text-xs text-ink-muted">
                    {t('admin.importExport.preview.showing', {
                      shown: PREVIEW_LIMIT,
                      total: rows.length
                    })}
                  </p>
                )}
              </div>
              <DataTable
                columns={previewColumns}
                rows={stats.display}
                rowClassName={(row) => (row.valid ? '' : 'bg-rose-50/40 dark:bg-rose-500/5')}
                emptyTitle={t('admin.importExport.preview.emptyTitle')}
                emptyText={t('admin.importExport.preview.emptyText')}
                maxHeight="32rem"
              />
            </div>
          </div>
        )}
      </section>
    </div>
  );
}
